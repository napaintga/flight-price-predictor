const I18nContext = createContext<{
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
} | null>(null);

const escapeRegExp = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const interpolate = (template: string, vars?: Record<string, string | number>) => {
  if (!vars) return template;

  return Object.entries(vars).reduce((result, [key, value]) => {
    const re = new RegExp(`\\{${escapeRegExp(key)}\\}`, "g");
    return result.replace(re, String(value));
  }, template);
};

export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [lang, setLang] = useState<Lang>("en");

  useEffect(() => {
    const stored = localStorage.getItem("lang");
    if (stored === "en" || stored === "uk") {
      setLang(stored);
      document.documentElement.lang = stored;
      return;
    }
    document.documentElement.lang = "en";
  }, []);

  const value = useMemo(
    () => ({
      lang,
      setLang: (next: Lang) => {
        setLang(next);
        localStorage.setItem("lang", next);
        document.documentElement.lang = next;
      },
      t: (key: string, vars?: Record<string, string | number>) => {
        const dict = translations[lang] ?? translations.en;
        const text = dict[key] ?? translations.en[key] ?? key;
        return interpolate(text, vars);
      }
    }),
    [lang]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return ctx;
};

export const formatPassengers = (count: number, lang: Lang) => {
  if (lang === "uk") {
    if (count === 1) return `${count} пасажир`;
    if (count >= 2 && count <= 4) return `${count} пасажири`;
    return `${count} пасажирів`;
  }
  return `${count} passenger${count === 1 ? "" : "s"}`;
};
